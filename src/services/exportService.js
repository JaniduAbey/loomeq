// Configuration Export Service for Google Home & Smart Speakers
// Generates ready-to-run configurations for Google Cast, pychromecast, CamillaDSP, and ALSA/PipeWire.

import { STANDARD_FREQUENCIES_10 } from '../audio/AudioEngine';

export function generateGoogleHomePayload(bass, treble) {
  return JSON.stringify(
    {
      settings: {
        system: {
          audio_eq: {
            bass: Number(bass.toFixed(1)),
            treble: Number(treble.toFixed(1)),
          },
        },
      },
    },
    null,
    2
  );
}

export function generatePythonPyChromecast(deviceName, bass, treble) {
  return `# Python script using pychromecast to configure Google Home EQ
import sys
import pychromecast

DEVICE_NAME = "${deviceName || 'Living Room Nest Audio'}"
BASS_DB = ${bass.toFixed(1)}
TREBLE_DB = ${treble.toFixed(1)}

print(f"Searching for Google Home device: {DEVICE_NAME}...")
chromecasts, browser = pychromecast.get_listed_chromecasts(friendly_names=[DEVICE_NAME])

if not chromecasts:
    print(f"Device '{DEVICE_NAME}' not found on local network.")
    sys.exit(1)

cast = chromecasts[0]
cast.wait()
print(f"Connected to {cast.name} ({cast.cast_info.host}:{cast.cast_info.port})")

# Google Home / Nest Audio Equalizer API
# In pychromecast, bass and treble range from -6.0 to +6.0 dB
try:
    # Eureka local setup API endpoint
    import requests
    url = f"http://{cast.cast_info.host}:8008/setup/set_eureka_info"
    payload = {
        "settings": {
            "system": {
                "audio_eq": {
                    "bass": BASS_DB,
                    "treble": TREBLE_DB
                }
            }
        }
    }
    resp = requests.post(url, json=payload, timeout=3.0)
    if resp.status_code == 200:
        print("Success! Google Home EQ updated successfully.")
    else:
        print(f"Failed with status {resp.status_code}: {resp.text}")
except Exception as e:
    print(f"Error communicating with device: {e}")
finally:
    pychromecast.discovery.stop_discovery(browser)
`;
}

export function generateCamillaDspConfig(bands10, roomMode = 'free', nightMode = false) {
  const filtersYaml = bands10
    .map((gain, i) => {
      const freq = STANDARD_FREQUENCIES_10[i];
      const type = i === 0 ? 'Lowshelf' : i === 9 ? 'Highshelf' : 'Peaking';
      return `  eq_band_${freq}hz:
    type: Biquad
    parameters:
      type: ${type}
      freq: ${freq}
      gain: ${gain.toFixed(1)}
      q: ${type === 'Peaking' ? '1.414' : '0.707'}`;
    })
    .join('\n');

  return `# CamillaDSP configuration for Custom Wireless Speaker / Raspberry Pi
title: "AuraEQ Custom Profile"
description: "Generated by AuraEQ Smart Speaker Suite"

pipeline:
  - type: Filter
    channel: 0
    names:
${bands10.map((_, i) => `      - eq_band_${STANDARD_FREQUENCIES_10[i]}hz`).join('\n')}
  - type: Filter
    channel: 1
    names:
${bands10.map((_, i) => `      - eq_band_${STANDARD_FREQUENCIES_10[i]}hz`).join('\n')}

filters:
${filtersYaml}
${roomMode === 'corner' ? `  room_corner_compensation:
    type: Biquad
    parameters:
      type: Lowshelf
      freq: 160
      gain: -4.5
      q: 0.707\n` : ''}
${nightMode ? `  night_compressor:
    type: Compressor
    parameters:
      threshold: -24.0
      ratio: 8.0
      attack: 0.003
      release: 0.250\n` : ''}`;
}

export function generateCurlCommand(deviceIp, bass, treble) {
  return `curl -X POST "http://${deviceIp || '192.168.1.42'}:8008/setup/set_eureka_info" \\
  -H "Content-Type: application/json" \\
  -d '{"settings":{"system":{"audio_eq":{"bass":${bass.toFixed(1)},"treble":${treble.toFixed(1)}}}}}'`;
}

export function downloadJsonFile(filename, data) {
  const blob = new Blob([JSON.stringify(data, null, 2)], { type: 'application/json' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
